/**
   Map a character from the wire protocol onto a glyph index. Anything we cannot
   draw becomes blank rather than reading past the end of the table -- the
   server already filters its output, so this is belt and braces.
*/
inline uint8_t glyphIndex(char c) {
  if (c >= '0' && c <= '9') return c - '0';
  if (c >= 'A' && c <= 'Z') return (c - 'A') + 10;
  if (c == '-') return 36;
  if (c == '+') return 37;
  return GLYPH_BLANK;
}

